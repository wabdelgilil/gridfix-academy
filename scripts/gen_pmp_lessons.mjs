function inlineGlossary(terms) {
  return terms
    .map(([term, def], i) => {
      const english =
        inlineEnglish[term] ??
        glossaryEnglishFallback[i % glossaryEnglishFallback.length];
      const cleaned = term
        .replace(/\*\*/g, '')
        .replace(/\s*\([^)]*\)\s*$/, '')
        .trim();
      return `- **${cleaned} (${english})**: ${def}`;
    })
    .join('\n');
}

function parseFrontmatter(text) {
  const parts = text.split('---');
  const raw = parts[1] ?? '';
  const out = {};
  let currentArray = null;
  for (const line of raw.split('\n')) {
    if (!line.trim()) continue;
    const arr = line.match(/^\s+-\s+(.*)$/);
    if (arr && currentArray) {
      out[currentArray].push(stripQuotes(arr[1].trim()));
      continue;
    }
    const m = line.match(/^([A-Za-z]+):\s*(.*)$/);
    if (!m) continue;
    const key = m[1];
    const value = m[2].trim();
    if (['objectives', 'objectivesEn', 'sources'].includes(key)) {
      out[key] = [];
      currentArray = key;
    } else {
      const text = stripQuotes(value);
      if (key === 'minutes' || key === 'order' || key === 'examWeight')
        out[key] = Number(text);
      else if (key === 'hasTool') out[key] = text === 'true';
      else out[key] = text;
      currentArray = null;
    }
  }
  return out;
}

function stripQuotes(v) {
  if (
    v.length >= 2 &&
    ((v[0] === '"' && v.at(-1) === '"') || (v[0] === "'" && v.at(-1) === "'"))
  ) {
    return v.slice(1, -1).replace(/''/g, "'").replace(/\\"/g, '"');
  }
  return v;
}

function yamlValue(v) {
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  return JSON.stringify(String(v));
}

function frontmatter(meta) {
  const lines = ['---'];
  for (const [k, v] of Object.entries(meta)) {
    if (Array.isArray(v)) {
      lines.push(`${k}:`);
      v.forEach((item) => lines.push(`  - ${yamlValue(item)}`));
    } else {
      lines.push(`${k}: ${yamlValue(v)}`);
    }
  }
  lines.push('---');
  return lines.join('\n');
}

